    # Design parameters from the design plan
    # Outer radius: 3.49 mm (from dimensions section, not the perturbed radius in LOOPS)
    # Inner radius: 2.0 mm
    # Extrude distance: 0.36 mm
    outer_radius = 3.49
    inner_radius = 2.0
